def render_record_inventory(inv: dict) -> str:
    out = ["# Site record inventory — civil works", "", GENERATED, "",
           "Descriptive only: nothing here is a finding against an invoice.", "",
           f"**{inv['total_records']} records** parsed from `civilwork/records/*.txt`.", "",
           _table(["Type", "Title", "Records", "Date range"],
                  [[p, t["title"], t["count"], " to ".join(t["date_range"]) if t["date_range"] else ""] for p, t in inv["types"].items()]), "",
           "## Parse and format checks", "",
           f"- Parse issues: {inv['parse_issue_counts'] or 'none'}"]
    for code, msgs in inv["parse_issues"].items():
        out += [f"  - `{code}`: " + "; ".join(msgs[:10])]
    out += [f"- Malformed records (structural issues): {inv['malformed_records'] or 'none'}",
            f"- Duplicate ticket ids: {inv['duplicate_tickets'] or 'none'}",
            f"- Gaps in ticket numbering: {inv['ticket_numbering_gaps'] or 'none'}",
            f"- Records without a usable date: {inv['records_without_date'] or 'none'}",
            f"- Missing or blank foreman signature: {inv['missing_foreman_signature'] or 'none'}",
            f"- Missing or blank Engineer's-representative countersignature: {inv['missing_engineer_signature'] or 'none'}",
            f"- Job line values: {inv['jobs']}",
            f"- Foremen: {inv['foremen']}",
            f"- Engineer's representatives: {inv['engineer_reps']}", "",
            "## Format variants", "",
            "- All types: title line, `Ticket`, `Job`, `Area`, a free-text description line, `Signed (foreman)`, `Countersigned (Engineer's representative)`. Files use CRLF line endings.",
            "- Single-day types carry `Date: DD/MM/YYYY`. DX and PT additionally carry `Ground:`.",
            "- DW (weekly) carries `Week beginning: DD/MM/YYYY` and `Days on: Tue 04/02, ...` (day/month without year, resolved into the 7-day window).", ""]
    for p, t in inv["types"].items():
        out += [f"## {p} — {t['title']} ({t['count']})", "", f"Areas: {t['areas']}"]
        if t["ground"]:
            out += [f"", f"Ground stated: {t['ground']}"]
        if "days_on_count" in t:
            out += ["", f"Days on per record: {t['days_on_count']}; week-beginning weekday: {t['week_beginning_weekday']}"]
        out += ["", "Description phrasing (numbers masked as N):", "",
                _table(["Pattern", "Records", "Example"], [[d["pattern"], d["count"], d["example"]] for d in t["description_patterns"]]), ""]
    return "\n".join(out) + "\n"


