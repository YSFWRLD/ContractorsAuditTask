def _duplicates(result) -> list[str]:
    lines, data = _lines(result), result.data
    apps = {a.application_no: a for a in data.applications}
    alt = next(a for a in result.alternatives if a.field == "measurement_order")
    alt_keys = {f.key for f in alt.run.findings}
    groups = defaultdict(list)
    for l in data.lines:
        if l.record_ref:
            groups[("record", l.record_ref)].append(l)
        groups[("item_area_date", l.item_code, l.site, l.work_date)].append(l)
    rows = []
    for key, members in sorted(groups.items(), key=lambda kv: str(kv[0])):
        if len(members) < 2:
            continue
        if key[0] == "record" and not any(f.category == "duplicate_record" and f.line_ref in {m.line_ref for m in members} for f in result.base.findings + alt.run.findings):
            continue
        by_sub = sorted(members, key=lambda l: (apps[l.application_no].application_date, l.application_no, l.line_no))
        by_num = sorted(members, key=lambda l: (l.application_no, l.line_no))
        dup_rules = {"duplicate_record", "duplicate_line"}
        working = sorted(f.line_ref for f in result.base.findings if f.category in dup_rules and f.line_ref in {m.line_ref for m in members})
        alternative = sorted(f.line_ref for f in alt.run.findings if f.category in dup_rules and f.line_ref in {m.line_ref for m in members})
        totals = sorted({m.application_no for m in members if result.base.contract_totals[m.application_no] != alt.run.contract_totals[m.application_no]})
        rows.append([key[1] if key[0] == "record" else f"{key[1]} {key[2]} {key[3]}",
                     "; ".join(f"{m.line_ref} (submitted {apps[m.application_no].application_date}, work {m.work_date})" for m in members),
                     by_sub[0].line_ref, by_num[0].line_ref, ", ".join(working), ", ".join(alternative),
                     "yes" if working != alternative else "no", ", ".join(totals) or "none"])
    changed = sum(r[6] == "yes" for r in rows)
    return ["## 5. Duplicate groups and the 'later measurement'", "",
            "Clause 44 disallows 'the later measurement'. The contract does not define 'later'; the working reading is the later submission "
            "(guideline 10: billed twice 'against an earlier one'), the alternative the higher application number. A third reading (later work "
            "date) has no textual anchor in Clause 44 and is not modelled.", "",
            _table(["Group", "Lines", "Kept (by submission)", "Kept (by number)", "Refused (working)", "Refused (alternative)", "Flag moves", "Totals change"], rows), "",
            f"{len(rows)} groups; the refused line moves between applications in {changed} of them. The dependency stays measured "
            "(`measurement_order`, MEDIUM) and every affected total is blank.", ""]


