def _category_matrix(result) -> list[str]:
    counts = Counter(f.category for f in result.findings)
    deps = defaultdict(set)
    for f in result.findings:
        for d in f.dependencies:
            if d.effect == "finding_absent":
                deps[f.category].add(f"{d.switch} ({d.band.value})")
    gained = defaultdict(set)
    base_keys = {f.key for f in result.base.findings}
    for a in result.alternatives:
        for f in a.run.findings:
            if f.key not in base_keys and a.band is not ConfidenceBand.HIGH:
                gained[f.category].add(f"{a.field} ({a.band.value})")
    effect = {c: ("no (breach only)" if c in NO_CONSEQUENCE_CATEGORIES or c in (Category.CONTRACT_REFERENCE_MISMATCH,)
                  else "outside the total" if c in (Category.ADJUSTMENT_MISSING, Category.ADJUSTMENT_INCORRECTLY_APPLIED, Category.RETENTION_INCORRECT)
                  else "blanks it" if c is Category.ITEM_NOT_IN_CONTRACT else "yes") for c in CATEGORIES}
    rows = [[c.value, int(CATEGORY_INFO[c].check), "; ".join(CATEGORY_INFO[c].clauses), CATEGORY_TESTS[c.value], counts.get(c.value, 0),
             effect[c], "; ".join(sorted(deps[c.value])) or "—", "; ".join(sorted(gained[c.value])) or "—"] for c in CATEGORIES]
    zero = [c.value for c in CATEGORIES if not counts.get(c.value)]
    return ["## 2. Category matrix", "",
            _table(["Category", "Check", "Clauses", "Test", "Findings", "Affects total", "Finding disappears under", "Extra findings appear under"], rows), "",
            f"Zero-occurrence categories ({len(zero)}): {', '.join(zero)}. Each is implemented and exercised by the synthetic test named above. "
            "`service_not_contracted_on_date` is not a civil works concept: no Schedule 1 item is limited to a date range, and the term itself is "
            "checked by `work_outside_contract_period` / `work_after_final_completion`; an item with no Schedule 1 rate is `item_not_in_contract`.", ""]


