def _split_lines(result) -> list[str]:
    terms = result.data.terms
    engine = PricingEngine(terms)
    lines, apps = _lines(result), {a.application_no: a for a in result.data.applications}
    checked = amount_ok = flagged_rate = 0
    problems = []
    for ref, v in sorted(result.base.lines.items()):
        cb = v.contract_billed
        if cb is None or not cb.is_split:
            continue
        checked += 1
        line = lines[ref]
        alloc = cb.band_allocation
        edges = {b.end for b in terms.bands[line.item_code] if b.end is not None}
        # Independent recomputation of the segmentation and each segment's rate.
        pre = engine.pre_band_rate(line_context(line, apps[line.application_no], engine.interp))
        total = Decimal(0)
        seg_ok = sum(s.quantity for s in alloc.slices) == line.quantity
        for s, part in zip(alloc.slices, cb.parts):
            seg_ok &= s.cumulative_to - s.cumulative_from == s.quantity
            rate = pre.value * s.percent_of_rate / 100
            for _, pct in pre.discount_factors:
                rate = rate * (1 - pct / 100)
            seg_ok &= round_built_up_rate(rate) == part.rate
            total += s.quantity * part.rate
        seg_ok &= all(Decimal(s.cumulative_to) in edges for s in alloc.slices[:-1])
        seg_ok &= int(total * 100) == cb.amount_cents
        if not seg_ok:
            problems.append(ref)
        amount_ok += line.amount_cents == cb.amount_cents
        flagged_rate += any(f.line_ref == ref and f.rule == "rates.unit_rate" for f in result.findings)
    split_findings = [f for f in result.findings if f.rule == "rates.band_split_amount"]
    return ["## 7. Band-split lines", "",
            _table(["Check", "Result"], [
                ["billed lines the contract divides at a band edge", checked],
                ["segmentation (slices sum to the quantity, cut exactly at band edges), segment rates (pre-band rate x band % x discounts, rounded once) and amount recomputed outside the ledger and equal to the engine", checked - len(problems)],
                ["recomputation mismatches", ", ".join(problems) or "none"],
                ["billed amount equals the contract split amount", amount_ok],
                ["split lines judged on their printed (pre-rebate) rate", flagged_rate],
                ["split-line amount findings", ", ".join(f"{f.line_ref} ({f.category})" for f in split_findings) or "none"],
            ]), ""]


def _totals(result) -> list[str]:
    engine = PricingEngine(result.data.terms)
    lines, apps = _lines(result), {a.application_no: a for a in result.data.applications}
    flagged = [a for a in result.applications if a.flagged]
    published = [a for a in flagged if a.expected_total_cents is not None]
    reconstructed, issues = 0, []
    for a in published:
        total = 0
        for l in result.data.lines:
            if l.application_no != a.application_no:
                continue
            v = result.base.lines[l.line_ref]
            if v.payable_quantity == 0:
                continue
            alloc = v.contract_payable.band_allocation
            total += engine.price(line_context(l, apps[l.application_no], engine.interp), v.payable_quantity, alloc).amount_cents
        ok = total == a.expected_total_cents and not any(d.band is not ConfidenceBand.HIGH for d in a.total_dependencies)
        reconstructed += ok
        if not ok:
            issues.append(a.application_no)
    blank = [a for a in flagged if a.expected_total_cents is None]
    excl = Counter(a.primary_blank_reason for a in blank)
    return ["## 8. Corrected totals", "",
            _table(["Measure", "Count"], [
                ["flagged applications", len(flagged)], ["published corrected totals", len(published)], ["blank corrected totals", len(blank)],
                ["published totals re-priced line by line from their payable quantities (fresh engine instance, same contract rules) and matched", reconstructed],
                ["published totals failing the check", ", ".join(issues) or "none"],
                ["published totals equal to the billed total (breach without a total effect)", sum(a.total_status == "unchanged" for a in published)],
            ]), "",
            "Blank totals, mutually exclusive primary reason:", "",
            _table(["Primary reason", "Applications"], sorted(excl.items(), key=lambda kv: (-kv[1], kv[0]))), "",
            "Unflagged rows carry `expected_total_cents = billed_total_cents`: the task asks for all 900 rows and a `0` is a claim that the total is right.", ""]


